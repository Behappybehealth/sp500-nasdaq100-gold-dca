"""session_state 键的单一登记处：键名常量 + 归属链 + 生命周期。

**为什么需要这个文件**：Streamlit 每次交互把整个脚本从头重跑，`st.session_state`
是唯一能跨重跑存活的载体——它实质上就是本应用的全局可变状态池。而它是 dict-like，
**写任意键都合法、拼错不报错**：`synced` 写成 `synched` 没有任何提示，
"本会话是否已同云端同步"从此永久判假（每趟都重同步）或永久判真
（建议基于陈旧缓存静默出错）。常量引用把这类拼写错从"静默建一个新键"
提前到 import 期 `ImportError` / `AttributeError`。

**本模块只定义名字与协议，不封装每个键的读写**：11 个键各包一层薄函数会多出
20 多个一行函数，还要逐个复刻 `pop` 的默认值语义、`get` 与 `in` 的差别——
业务代码继续直接写 `st.session_state[K_XXX]`，Streamlit 原生语义一个不丢。
唯一的例外是 `invalidate_sync()`：它不是"包装读写"，而是收敛一条**跨模块协议**
（见函数注释）。

⚠️ **命名空间是共享的**：widget 的 `key=` 参数与这里的业务键住在同一个 dict 里。
当前 7 个（2026-08-21 实测）：`back_login` / `btn_logout` / `btn_import` /
`btn_dup_cancel` / `btn_save_budget` / `amt_base` / `budget_in`。新增业务键前先确认
不与它们撞名（`tests/test_state.py` 有断言兜着）。widget key 本身不进本表——
它们是 Streamlit 的局部控件标识，与跨重跑的业务状态不同类，硬凑一张表会误导。

登出走 `src/ui/sidebar.py` 的 `st.session_state.clear()` 全清，本表所有键一并消失。
这是当前正确行为（切用户不会残留上一个用户的暂存），但它同时是个**隐式契约**：
将来若引入应当跨登出保留的键（UI 偏好之类），必须回来改那一处。
"""
from __future__ import annotations

import streamlit as st

# ============================================================
# 认证链（src/ui/auth.py 独占读写）
# ============================================================

#: 已登录用户名（storage 侧的规范大小写）。**存在即视为已登录**——这是门闸判据本身。
#: 生命周期：登录/激活/自举成功时写入 → 登出 `clear()` 全清。
K_USER = "user"

#: 点击那一趟暂存的表单输入（`stage` + 名字 + PIN），供下一趟运行消费。
#: ⚠️ **含明文 PIN**：只在内存里活一趟，绝不可落日志、落盘、进异常消息
#: （`tests/test_obs.py` 有断言禁止日志调用点引用它的字段）。
#: 生命周期：表单提交时写入 → 下一趟消费后立即 `pop`（三个 stage 分支各 pop 一次）。
K_AUTH = "_auth"

#: 用户名单的会话缓存。存在它是"登录页整趟零网络请求"的前提——
#: 遮罩要在点击后立刻出现，那一趟就不能触网。
#: 生命周期：会话首次渲染登录页时触网加载一次 → 登录/自举后顺手刷新 → 登出全清。
K_NAMES = "_names"

#: 待激活的用户名（管理员已开通但本人还没设 PIN）。存在它就把登录页切成"设置 PIN"态。
#: 生命周期：认证返回 `pending` 时写入 → 设 PIN 成功或点"返回登录"时 `pop`。
K_ACTIVATING = "activating"

#: 一次性错误消息，三条链各一个：登录页 / 设置 PIN 页 / 自举页。
#: 生命周期都是**写一次读一次**——渲染时 `pop` 即消费，所以刷新页面不会重复报错。
K_LOGIN_ERR = "_login_err"
K_ACT_ERR = "_act_err"
K_BOOT_ERR = "_boot_err"

# ============================================================
# 同步链（唯一的跨模块共享键）
# ============================================================

#: 本会话是否已把云端数据拉到本地缓存（`storage.sync_local`）。
#: 置位归认证链（`src/ui/auth.py`，四处：登录后/激活后/自举后/会话首同步后）；
#: 判读也在那里。**失效化统一走 `invalidate_sync()`**，别在别处写 `pop`。
K_SYNCED = "synced"

# ============================================================
# 记账链（src/tabs/records.py 独占读写）
# ============================================================

#: 待确认的成交记录（填表 → 复述 → 落库 三段式的中间态）。
#: 生命周期：生成复述时写入 → 确认写入成功 / 点取消时 `pop`。
K_PENDING_TX = "pending_tx"

#: 去重拦截的提示文本（同日同资产同方向已有记录时，storage 抛的 `ValueError`）。
#: 存在它就多渲染一组"仍要写入 / 取消"按钮。
#: 生命周期：写入被拦时写入 → 强制写入成功 / 点取消时 `pop`。
K_TX_DUP = "tx_dup"

#: 待确认的观察（跳过）记录，与 `K_PENDING_TX` 同构。
K_PENDING_OBS = "pending_obs"


#: 登记表全集。`tests/test_state.py` 用它断言**登记表与实际用键互相覆盖**——
#: 既不许有未登记的键（新键绕过本文件），也不许有死常量（键没了常量还在）。
ALL_KEYS: frozenset[str] = frozenset(
    {
        K_USER,
        K_AUTH,
        K_NAMES,
        K_ACTIVATING,
        K_LOGIN_ERR,
        K_ACT_ERR,
        K_BOOT_ERR,
        K_SYNCED,
        K_PENDING_TX,
        K_TX_DUP,
        K_PENDING_OBS,
    }
)


def invalidate_sync() -> None:
    """丢掉同步标记，让下一趟运行重新从云端拉一次。

    这是本模块唯一的函数，理由是它收敛的不是"读写"而是一条**跨模块协议**：
    置位在 `src/ui/auth.py`（同步刚成功那一行后面），而想触发重同步的人在别处
    （侧栏 🔄）。协议原先只体现为一句 `pop("synced")`，第三处想触发重同步得先
    知道这个隐式约定存在——而它没写在任何地方。现在它是个能被 grep 到的名字。
    """
    st.session_state.pop(K_SYNCED, None)
